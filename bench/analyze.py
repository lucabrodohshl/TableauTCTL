"""Turn a JSONL run into the paper's figures and tables.

Reads the records written by :mod:`runner` and emits, for each research
question, one LaTeX table and (where a trend is the point) one figure.  Nothing
here re-runs the solver, so the analysis can be iterated on a finished run.
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path
from typing import Dict, List

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt   # noqa: E402


def load(path: Path) -> List[dict]:
    return [json.loads(l) for l in path.read_text().splitlines() if l.strip()]


def _tex_escape(s: str) -> str:
    return s.replace("_", r"\_")


# ── RQ1 ─────────────────────────────────────────────────────────────────────

def rq1_table(recs: List[dict], out: Path) -> None:
    rows = []
    for fam, axis, label in (("depth", "depth", "nesting depth"),
                             ("clocks", "k", "live clocks"),
                             ("constant", "M", "max constant $M$"),
                             ("size", "n", "formula size")):
        fr = [r for r in recs if r["family"] == fam]
        for verdict in ("SAT", "UNSAT"):
            sel = [r for r in fr if r.get("expected") == verdict]
            if not sel:
                continue
            solved = [r for r in sel if r["verdict"] != "TIMEOUT"]
            nodes = [r["nodes"] for r in solved if r["nodes"] is not None]
            rows.append((label, verdict, len(sel), len(sel) - len(solved),
                         max((r["time_s"] for r in solved), default=0.0),
                         max(nodes, default=0)))
    with out.open("w") as f:
        f.write("% generated by bench/analyze.py -- do not edit\n")
        f.write(r"\begin{table}[t]\centering" "\n")
        f.write(r"\caption{\textbf{RQ1: cost drivers.} Per family and verdict: "
                r"instances, timeouts at the 300\,s ceiling, worst solved time "
                r"and worst tableau-node count.}\label{tab:perf-rq1}" "\n")
        f.write(r"\begin{tabular}{llrrrr}\toprule" "\n")
        f.write(r"driver & verdict & \#inst & timeouts & max time (s) & max nodes\\\midrule" "\n")
        for label, verdict, n, to, t, nd in rows:
            f.write(f"{label} & {verdict} & {n} & {to} & {t:.2f} & {nd}\\\\\n")
        f.write(r"\bottomrule\end{tabular}\end{table}" "\n")


def rq1_figure(recs: List[dict], out: Path, timeout_s: float = 300.0) -> None:
    panels = [("depth", "depth", "(a) nesting depth"),
              ("clocks", "k", "(b) live clocks"),
              ("constant", "M", "(c) max constant $M$"),
              ("size", "n", "(d) formula size")]
    fig, axes = plt.subplots(2, 2, figsize=(7.2, 5.0))
    for ax, (fam, key, title) in zip(axes.flat, panels):
        for verdict, marker in (("SAT", "o"), ("UNSAT", "s")):
            sel = sorted((r for r in recs
                          if r["family"] == fam and r.get("expected") == verdict),
                         key=lambda r: r["params"][key])
            if not sel:
                continue
            xs = [r["params"][key] for r in sel]
            ys = [r["time_s"] for r in sel]
            ax.plot(xs, ys, marker=marker, ms=3.5, lw=1.1, label=verdict)
            tox = [x for x, r in zip(xs, sel) if r["verdict"] == "TIMEOUT"]
            ax.plot(tox, [timeout_s] * len(tox), "x", color="k", ms=6)
        ax.set_yscale("log")
        if fam in ("constant", "size"):
            ax.set_xscale("log", base=2)
        ax.axhline(timeout_s, ls=":", lw=0.8, color="grey")
        ax.set_title(title, fontsize=9)
        ax.set_ylabel("median time (s)", fontsize=8)
        ax.tick_params(labelsize=7)
        ax.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(out)
    plt.close(fig)


# ── RQ2 ─────────────────────────────────────────────────────────────────────

def rq2_table(recs: List[dict], out: Path) -> None:
    fams = sorted({r["family"] for r in recs if r["rq"] == "RQ2"})
    with out.open("w") as f:
        f.write("% generated by bench/analyze.py -- do not edit\n")
        f.write(r"\begin{table}[t]\centering" "\n")
        f.write(r"\caption{\textbf{RQ2: \textsc{Uppaal}-shaped queries.} "
                r"Every shape is solved over the whole sweep, with no timeout.}"
                r"\label{tab:perf-rq2}" "\n")
        f.write(r"\begin{tabular}{lrrrrr}\toprule" "\n")
        f.write(r"query shape & \#inst & solved & max time (s) & max mem (MB) & max nodes\\\midrule" "\n")
        for fam in fams:
            sel = [r for r in recs if r["family"] == fam]
            solved = [r for r in sel if r["verdict"] != "TIMEOUT"]
            mem = [r["peak_mem_kb"] for r in solved if r["peak_mem_kb"]]
            nodes = [r["nodes"] for r in solved if r["nodes"] is not None]
            f.write(f"{_tex_escape(fam)} & {len(sel)} & {len(solved)} & "
                    f"{max((r['time_s'] for r in solved), default=0):.2f} & "
                    f"{max(mem, default=0)/1024:.2f} & {max(nodes, default=0)}\\\\\n")
        f.write(r"\bottomrule\end{tabular}\end{table}" "\n")


def cactus(recs: List[dict], out: Path, timeout_s: float = 300.0) -> None:
    fig, ax = plt.subplots(figsize=(4.4, 3.2))
    for rq, label in (("RQ2", "flat UPPAAL-shaped (RQ2)"),
                      ("RQ1", "adversarial nested (RQ1)")):
        ts = sorted(r["time_s"] for r in recs
                    if r["rq"] == rq and r["verdict"] != "TIMEOUT")
        ax.plot(ts, range(1, len(ts) + 1), lw=1.3, label=label)
    ax.axvline(timeout_s, ls=":", lw=0.9, color="grey")
    ax.set_xscale("log")
    ax.set_xlabel("per-instance median time (s)", fontsize=8)
    ax.set_ylabel("instances solved", fontsize=8)
    ax.tick_params(labelsize=7)
    ax.legend(fontsize=7, loc="lower right")
    fig.tight_layout()
    fig.savefig(out)
    plt.close(fig)


# ── RQ3 ─────────────────────────────────────────────────────────────────────

def rq3_table(recs: List[dict], out: Path) -> None:
    """Incompleteness rate, split by punctuality and nesting depth.

    Every RQ3 instance is satisfiable by construction, so an UNSATISFIABLE
    verdict is an incompleteness instance and a SATISFIABLE one is a hit.
    """
    sel = [r for r in recs if r["rq"] == "RQ3" and r.get("expected") == "SAT"]
    cells: Dict[tuple, List[dict]] = defaultdict(list)
    for r in sel:
        cells[(r["params"]["punctual"], r["params"]["depth"])].append(r)
    depths = sorted({d for _, d in cells})

    with out.open("w") as f:
        f.write("% generated by bench/analyze.py -- do not edit\n")
        f.write(r"\begin{table}[t]\centering" "\n")
        f.write(r"\caption{\textbf{RQ3: the completeness gap.} Every instance is "
                r"satisfiable by construction (witness $W$: one location, all atoms "
                r"true, divergent time), so an \UNSAT{} verdict is a missed model. "
                r"Entries are missed/total.}\label{tab:rq3-completeness}" "\n")
        f.write(r"\begin{tabular}{l" + "r" * len(depths) + r"}\toprule" "\n")
        f.write("interval & " + " & ".join(f"depth {d}" for d in depths)
                + r"\\\midrule" "\n")
        for punct, label in ((False, "non-punctual $[a,b]$, $a<b$"),
                             (True, "punctual $[a,a]$")):
            row = [label]
            for d in depths:
                grp = cells.get((punct, d), [])
                miss = sum(1 for r in grp if r.get("incomplete"))
                row.append(f"{miss}/{len(grp)}" if grp else "--")
            f.write(" & ".join(row) + r"\\" "\n")
        f.write(r"\bottomrule\end{tabular}\end{table}" "\n")


def rq3_summary(recs: List[dict]) -> str:
    allr = [r for r in recs if r["rq"] == "RQ3"]
    if not allr:
        return "RQ3: no instances"
    # Only the satisfiable-by-construction instances can exhibit incompleteness;
    # the UNSAT controls exist to show the pipeline would notice one.
    sel = [r for r in allr if r.get("expected") == "SAT"]
    ctl = [r for r in allr if r.get("expected") == "UNSAT"]
    miss = [r for r in sel if r.get("incomplete")]
    unsound = [r for r in allr if r.get("unsound")]
    warned_miss = [r for r in miss if r.get("warned_incomplete")]
    ctl_ok = sum(1 for r in ctl if r.get("agrees"))
    lines = [f"RQ3: {len(sel)} satisfiable-by-construction instances, "
             f"{len(miss)} missed ({100*len(miss)/len(sel):.1f}%)",
             f"     negative controls: {ctl_ok}/{len(ctl)} correctly refuted",
             f"     soundness violations: {len(unsound)}"]
    for punct in (False, True):
        grp = [r for r in sel if r["params"]["punctual"] == punct]
        gm = [r for r in grp if r.get("incomplete")]
        kind = "punctual    " if punct else "non-punctual"
        lines.append(f"     {kind}: {len(gm)}/{len(grp)} missed")
    if miss:
        lines.append(f"     of the missed, {len(warned_miss)} were flagged by the "
                     f"solver's own completeness warning")
        by_depth = defaultdict(int)
        for r in miss:
            by_depth[r["params"]["depth"]] += 1
        lines.append("     missed by nesting depth: "
                     + ", ".join(f"d{d}={n}" for d, n in sorted(by_depth.items())))
    return "\n".join(lines)


# ── Entry point ─────────────────────────────────────────────────────────────

def analyze(results: Path, figs: Path, tables: Path) -> None:
    recs = load(results)
    figs.mkdir(parents=True, exist_ok=True)
    tables.mkdir(parents=True, exist_ok=True)
    rq1_table(recs, tables / "T1_rq1_drivers.tex")
    rq1_figure(recs, figs / "fig_drivers.pdf")
    rq2_table(recs, tables / "T2_rq2_envelope.tex")
    cactus(recs, figs / "fig_perf_cactus.pdf")
    rq3_table(recs, tables / "T3_rq3_completeness.tex")
    print(rq3_summary(recs))
    bad = [r for r in recs if r.get("unsound")]
    if bad:
        print(f"\n!! {len(bad)} SOUNDNESS VIOLATIONS:")
        for r in bad[:10]:
            print(f"   {r['name']}: {r['formula'][:70]}")
